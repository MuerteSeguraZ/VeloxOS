; isr.asm — IRQ stubs for Velox OS
; Each stub saves all registers, calls irq_dispatch(irq_num), restores and irets

BITS 64

extern irq_dispatch

%macro IRQ_STUB 1
global irq_stub_%1
irq_stub_%1:
    push rax
    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push rbp
    push r8
    push r9
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15
    mov rdi, %1          ; first arg = IRQ number
    call irq_dispatch
    pop r15
    pop r14
    pop r13
    pop r12
    pop r11
    pop r10
    pop r9
    pop r8
    pop rbp
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx
    pop rax
    iretq
%endmacro

